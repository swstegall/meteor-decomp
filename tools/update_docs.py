"""
Regenerate the sentinel-delimited `progress` regions in the headline docs.

Pulls the durable solved-set numbers from `tools/progress.py --json`
(equivalently `docs/reconcile-state.json`, which `tools/reconcile.py`
writes from the same logic) and rewrites ONLY the content between

    <!-- BEGIN:progress -->
    ...generated...
    <!-- END:progress -->

in README.md, docs/decomp-status.md, and PLAN.md. Each file gets a
file-shaped rendering of the same numbers (full table for README +
decomp-status, a one-line summary for PLAN).

Guarantees:
  - **Idempotent.** Run twice → no diff.
  - **Byte-for-byte preservation outside the sentinels.** Only the
    region body changes; the sentinel comment lines and everything else
    are untouched.
  - **No-op when numbers are unchanged** — the file is only rewritten
    when its bytes would actually change (no churn, no mtime bump).
  - **No timestamps.** Nothing here reads the clock, so the output is
    stable across runs (the docs keep their own static "Last update:"
    line, which this tool never touches).

Line-oriented discipline mirrors `tools/update_yaml_status.py`.

Usage:
  tools/update_docs.py            # rewrite the three docs in place
  tools/update_docs.py --check    # exit non-zero if any doc is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Reuse progress.py's JSON so docs can never disagree with `make progress`.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from progress import collect_json  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent

BEGIN = "<!-- BEGIN:progress -->"
END = "<!-- END:progress -->"

# Display order + the ".exe" labels used in the doc tables.
BIN_ORDER = ("ffxivgame", "ffxivboot", "ffxivlogin", "ffxivupdater", "ffxivconfig")


def _fmt(n: int) -> str:
    return f"{n:,}"


def _pct(data: dict) -> str:
    return f"{data['totals']['pct_bytes']:.2f}"


def _rows(data: dict) -> list[tuple[str, dict]]:
    bins = data["binaries"]
    return [(b, bins[b]) for b in BIN_ORDER if b in bins]


def render_table_block(data: dict) -> str:
    """Full per-binary table — used by README.md and docs/decomp-status.md."""
    t = data["totals"]
    lines = [
        "`_rosetta/*.cpp` solved set across all five binaries "
        f"(**{_fmt(t['rosetta_count'])} files / {_fmt(t['rosetta_bytes'])} B / "
        f"{_pct(data)} %**):",
        "",
        "| Binary | `_rosetta/*.cpp` files | bytes | total bytes |",
        "|---|---:|---:|---:|",
    ]
    for stem, b in _rows(data):
        lines.append(
            f"| `{stem}.exe` | {_fmt(b['rosetta_count'])} | "
            f"{_fmt(b['rosetta_bytes'])} | {_fmt(b['total_bytes'])} |"
        )
    lines.append(
        f"| **Total** | **{_fmt(t['rosetta_count'])}** | "
        f"**{_fmt(t['rosetta_bytes'])}** | **{_fmt(t['total_bytes'])}** |"
    )
    return "\n".join(lines)


def render_plan_line(data: dict) -> str:
    """One-liner — used by PLAN.md."""
    t = data["totals"]
    return (
        f"**Current recovered-match count:** {_fmt(t['rosetta_count'])} "
        f"`_rosetta/*.cpp` files / {_fmt(t['rosetta_bytes'])} B ({_pct(data)} %) "
        "across all five binaries (regenerated by `make update-docs` from "
        "`make reconcile`)."
    )


# (path relative to repo root, body-renderer).
TARGETS = {
    "README.md": render_table_block,
    "docs/decomp-status.md": render_table_block,
    "PLAN.md": render_plan_line,
}


def replace_region(text: str, new_body: str, rel: str) -> str:
    """Swap the text between the BEGIN/END sentinels for `new_body`.

    Line-oriented: the BEGIN and END sentinel lines themselves are
    preserved verbatim; everything before BEGIN and after END is byte-
    for-byte untouched. Raises if the sentinels are missing/disordered.
    """
    lines = text.splitlines(keepends=True)
    begin_idx = end_idx = None
    for i, line in enumerate(lines):
        stripped = line.rstrip("\n").strip()
        if stripped == BEGIN:
            if begin_idx is not None:
                raise ValueError(f"{rel}: duplicate {BEGIN}")
            begin_idx = i
        elif stripped == END:
            if begin_idx is None:
                raise ValueError(f"{rel}: {END} before {BEGIN}")
            end_idx = i
            break

    if begin_idx is None or end_idx is None:
        raise ValueError(f"{rel}: missing {BEGIN}/{END} sentinel pair")

    # Reassemble: [.. BEGIN line] + body + [END line ..]. The body is
    # always newline-terminated so the END sentinel sits on its own line.
    head = lines[: begin_idx + 1]
    tail = lines[end_idx:]
    body = new_body if new_body.endswith("\n") else new_body + "\n"
    return "".join(head) + body + "".join(tail)


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if any doc's progress region is stale (no write)",
    )
    args = ap.parse_args()

    data = collect_json()

    print("=== update_docs ===")
    stale = False
    for rel, renderer in TARGETS.items():
        path = REPO_ROOT / rel
        if not path.exists():
            print(f"  {rel}: missing — skipping")
            continue
        original = path.read_text()
        updated = replace_region(original, renderer(data), rel)
        if updated == original:
            print(f"  {rel}: up to date")
            continue
        stale = True
        if args.check:
            print(f"  {rel}: STALE")
        else:
            path.write_text(updated)
            print(f"  {rel}: updated")

    if args.check and stale:
        print("update_docs: some docs are stale — run 'make update-docs'", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
